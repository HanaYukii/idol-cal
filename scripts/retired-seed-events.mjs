// Regenerates src/db/retiredSeedEvents.ts: every event the demo data has
// shipped in any commit on this branch that the working-tree seed no longer
// contains. Run after editing src/lib/seedData.ts (before committing):
//
//   node scripts/retired-seed-events.mjs
//
// The loader deletes leftover rows that match these signatures, which is what
// keeps a renamed or re-cast event from showing up twice on existing devices.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const SEED = 'src/lib/seedData.ts'
const OUT = 'src/db/retiredSeedEvents.ts'

const schema = readFileSync('src/db/schema.ts', 'utf8')
const removedArtists = new Set(
  [...(schema.match(/REMOVED_ARTIST_NAMES = \[([^\]]*)\]/)?.[1] ?? '').matchAll(/'([^']+)'/g)]
    .map((m) => m[1]),
)

/** Pull [date, title, names] out of one version of seedData.ts. */
function parse(src) {
  const start = src.indexOf('const EVENTS')
  if (start < 0) return []
  const cut = ['// Keep artist order', 'export async function']
    .map((marker) => src.indexOf(marker, start))
    .filter((i) => i > 0)
  const body = src.slice(start, Math.min(...cut, src.length))
  // Title constants are plain string literals; evaluate them so titles written
  // as templates, concatenations or bare identifiers all resolve the same way.
  const consts = {}
  for (const m of src.matchAll(/^const ([A-Z][A-Z0-9_]*) =\s*\n?\s*((['"`])(?:\\.|(?!\3)[^\\])*\3)\s*$/gm)) {
    consts[m[1]] = Function(`return ${m[2]}`)()
  }
  const names = Object.keys(consts)
  const values = names.map((n) => consts[n])
  const objects = body.match(/\{[^{}]*artistNames[\s\S]*?\n {2}\}/g) ?? []
  return objects.map((o) => {
    const expr = o.match(/\n {4}title: (.*),\n/)?.[1]
    const date = o.match(/date: '([^']+)'/)?.[1]
    if (!expr || !date) throw new Error(`unparsable seed entry:\n${o.slice(0, 200)}`)
    const title = String(Function(...names, `return (${expr})`)(...values)).trim()
    const artists = [...(o.match(/artistNames: \[([^\]]*)\]/)?.[1] ?? '').matchAll(/'([^']+)'/g)]
      .map((m) => m[1].trim().normalize('NFC'))
      .filter((n) => !removedArtists.has(n))
    return [date, title, [...new Set(artists)].sort()]
  })
}

const key = ([date, title, names]) => JSON.stringify([date, title, names])
const current = new Set(parse(readFileSync(SEED, 'utf8')).map(key))

const retired = new Map()
for (const commit of execSync(`git log --format=%H -- ${SEED}`, { encoding: 'utf8' }).trim().split('\n')) {
  let src
  try { src = execSync(`git show ${commit}:${SEED}`, { encoding: 'utf8', maxBuffer: 1 << 28 }) }
  catch { continue }
  let entries
  try { entries = parse(src) } catch (err) {
    console.warn(`skipped ${commit.slice(0, 7)}: ${err.message.split('\n')[0]}`)
    continue
  }
  for (const entry of entries) {
    if (entry[2].length === 0) continue // only removed artists: the artist cleanup handles it
    const k = key(entry)
    if (!current.has(k)) retired.set(k, entry)
  }
}

const rows = [...retired.values()].sort((a, b) => key(a).localeCompare(key(b)))
const lit = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync(OUT, `// Generated by scripts/retired-seed-events.mjs — do not edit by hand.

/**
 * [date, title, artists] of every event the demo data used to ship and no
 * longer does. A row still matching one of these after a sync is a leftover
 * from an older load (usually the pre-rename copy of an event).
 */
export const RETIRED_SEED_EVENTS: ReadonlyArray<readonly [string, string, readonly string[]]> = [
${rows.map(([d, t, n]) => `  [${lit(d)}, ${lit(t)}, [${n.map(lit).join(', ')}]],`).join('\n')}
]
`)
console.log(`${OUT}: ${rows.length} retired signatures (${current.size} current)`)
